"""
DeepSeek-Style Chain-of-Thought (CoT) Parser & Biocognitive Reasoning Module.
Provides deterministic separation between internal reasoning channels (<thought> ... </thought>)
and user-facing clean verbal responses, ensuring Zero-Leakage of tags, control tokens, and telemetry.
"""

from dataclasses import asdict, dataclass, field
from datetime import datetime
import re
from typing import Any, Dict, Optional, Tuple, Union


@dataclass
class BiocognitiveReasoning:
    """
    Structured first-class representation of the biocognitive reasoning channel (DeepSeek-Style).
    Preserves endogenous CoT reflections and internal states without leaking them into public speech.
    """
    thought_text: str
    qualia: Dict[str, float]
    neurochemistry: Dict[str, float]
    introspective_prediction: Dict[str, Any]
    epistemic_surprise: Dict[str, Any]
    clean_response: str
    dialogic_directive: str = ""
    raw_chatml_prompt: Optional[str] = None
    timestamp: str = field(default_factory=lambda: datetime.utcnow().isoformat())

    def to_dict(self) -> Dict[str, Any]:
        """Serializes the reasoning state to a standard dictionary."""
        return asdict(self)

    def summary(self) -> str:
        """Returns a concise one-line summary of the reasoning step."""
        q = self.qualia or {}
        dom = max(self.neurochemistry, key=self.neurochemistry.get) if self.neurochemistry else "N/A"
        loss_p = self.introspective_prediction.get("loss_p", 0.0) if self.introspective_prediction else 0.0
        return (
            f"[CoT: L={q.get('L', 0):.2f}, Q={q.get('Q', 0):.2f}, E={q.get('E', 0):.2f} "
            f"| Dom={dom} | Loss_p={loss_p:.4f}]"
        )


class DeepSeekCoTParser:
    """
    Deterministic parser for DeepSeek-style Chain-of-Thought decoupling.
    Enforces strict Zero-Leakage:
      - Extracts and strips <thought>...</thought> and <think>...</think> blocks.
      - Resilient to early truncation (unclosed <thought> tags).
      - Resilient to mixed/malformed tags.
      - Scrubs ChatML control tokens (<|im_start|>, <|im_end|>, etc.).
      - Scrubs residual synthetic tags and raw numeric telemetry.
    """

    THOUGHT_PATTERN = re.compile(
        r"<(?:thought|think)>(.*?)</(?:thought|think)>",
        re.DOTALL | re.IGNORECASE
    )
    UNCLOSED_THOUGHT_PATTERN = re.compile(
        r"<(?:thought|think)>(.*)",
        re.DOTALL | re.IGNORECASE
    )
    CONTROL_TOKENS_PATTERN = re.compile(
        r"<\|im_start\|>|<\|im_end\|>|<\|endoftext\|>|<bos>|<eos>|<pad>",
        re.IGNORECASE
    )
    RESIDUAL_TAGS_PATTERN = re.compile(
        r"</?(?:thought|think)>",
        re.IGNORECASE
    )
    TELEMETRY_PATTERN = re.compile(
        r"\[Homeostase Qualia:[^\]]*\]|"
        r"\[Neurotransmissores:[^\]]*\]|"
        r"\[Predição Introspectiva[^\]]*\]|"
        r"\[Surpresa Epistêmica[^\]]*\]|"
        r"\[Diretriz Dialógica:[^\]]*\]|"
        r"\(L=\d+\.\d+,\s*Q=\d+\.\d+(?:,\s*E=\d+\.\d+)?\)|\(L=\d+\.\d+\)|"
        r"\bloss_p=\d+\.\d+",
        re.IGNORECASE
    )

    @classmethod
    def parse(
        cls,
        raw_output: str,
        fallback_thought: str = ""
    ) -> Tuple[str, str]:
        """
        Parses raw model generation into (thought_channel, clean_verbal_response).

        Args:
            raw_output: Raw text generated by model or adapter.
            fallback_thought: Optional fallback thought text if none present in output.

        Returns:
            thought_channel: Cleaned internal thought text without delimiting tags.
            clean_verbal_response: Sanitized verbal response guaranteed 100% free of
                                   tags, control tokens, and raw telemetry.
        """
        if not raw_output:
            fallback = cls.sanitize_thought(fallback_thought)
            return fallback, ""

        thought_parts = []
        clean_text = raw_output

        # 1. Extract all closed thought/think blocks
        closed_matches = list(cls.THOUGHT_PATTERN.finditer(raw_output))
        if closed_matches:
            for m in closed_matches:
                inner = m.group(1).strip()
                if inner:
                    thought_parts.append(inner)
            # Remove all closed thought blocks from the verbal response
            clean_text = cls.THOUGHT_PATTERN.sub("", clean_text)
        else:
            # 2. Check for unclosed / truncated thought block (e.g. generation cut off)
            unclosed_match = cls.UNCLOSED_THOUGHT_PATTERN.search(raw_output)
            if unclosed_match:
                inner = unclosed_match.group(1).strip()
                if inner:
                    thought_parts.append(inner)
                # Ensure truncated thought NEVER leaks into verbal response
                clean_text = cls.UNCLOSED_THOUGHT_PATTERN.sub("", clean_text)

        thought_extracted = "\n".join(thought_parts).strip()
        if not thought_extracted and fallback_thought:
            thought_extracted = fallback_thought.strip()

        # Sanitize thought text itself (no control tokens or residual enclosing tags)
        thought_extracted = cls.sanitize_thought(thought_extracted)

        # 3. Deep sanitization of the verbal response
        clean_text = cls.CONTROL_TOKENS_PATTERN.sub("", clean_text)
        clean_text = cls.RESIDUAL_TAGS_PATTERN.sub("", clean_text)
        clean_text = cls.TELEMETRY_PATTERN.sub("", clean_text)

        # 4. Spacing and whitespace normalization
        clean_text = re.sub(r"[ \t]+", " ", clean_text)
        clean_text = re.sub(r" ?\n ?", "\n", clean_text)
        clean_text = re.sub(r"\n{3,}", "\n\n", clean_text)
        clean_text = clean_text.strip()

        return thought_extracted, clean_text

    @classmethod
    def parse_generation(
        cls,
        raw_output: str,
        fallback_thought: str = ""
    ) -> Tuple[str, str]:
        """Alias for parse() to support canonical naming across callers."""
        return cls.parse(raw_output, fallback_thought=fallback_thought)

    @classmethod
    def sanitize_thought(cls, text: str) -> str:
        """Removes control tokens and thought tags from extracted reasoning text."""
        if not text:
            return ""
        s = cls.CONTROL_TOKENS_PATTERN.sub("", text)
        s = cls.RESIDUAL_TAGS_PATTERN.sub("", s)
        return s.strip()
