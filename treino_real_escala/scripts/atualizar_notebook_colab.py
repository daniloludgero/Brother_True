# Cell 10: Code 5
cell_10_lines = [
    "# @title 5. Definição da Arquitetura Voz Distribuída 158M (RoPE 20k + SwiGLU)\n",
    "import math\n",
    "import torch\n",
    "import torch.nn as nn\n",
    "import torch.nn.functional as F\n",
    "\n",
    "class HumorProjector(nn.Module):\n",
    "    def __init__(self, dim_humor=11, d_model=768, hidden_dim=256):\n",
    "        super().__init__()\n",
    "        self.net = nn.Sequential(\n",
    "            nn.Linear(dim_humor, hidden_dim),\n",
    "            nn.GELU(),\n",
    "            nn.LayerNorm(hidden_dim),\n",
    "            nn.Linear(hidden_dim, d_model),\n",
    "            nn.LayerNorm(d_model)\n",
    "        )\n",
    "    def forward(self, humor):\n",
    "        if humor.dim() == 1:\n",
    "            humor = humor.unsqueeze(0)\n",
    "        return self.net(humor).unsqueeze(1)\n",
    "\n",
    "class SwiGLU(nn.Module):\n",
    "    def __init__(self, d_model, hidden_dim, dropout=0.1):\n",
    "        super().__init__()\n",
    "        self.w_gate = nn.Linear(d_model, hidden_dim, bias=False)\n",
    "        self.w_up = nn.Linear(d_model, hidden_dim, bias=False)\n",
    "        self.w_down = nn.Linear(hidden_dim, d_model, bias=False)\n",
    "        self.dropout = nn.Dropout(dropout)\n",
    "    def forward(self, x):\n",
    "        return self.dropout(self.w_down(F.silu(self.w_gate(x)) * self.w_up(x)))\n",
    "\n",
    "class RotaryEmbedding(nn.Module):\n",
    "    def __init__(self, dim, max_seq_len=20480, base=500000.0):\n",
    "        super().__init__()\n",
    "        self.dim = dim\n",
    "        self.max_seq_len = max_seq_len\n",
    "        inv_freq = 1.0 / (base ** (torch.arange(0, dim, 2, dtype=torch.float32) / dim))\n",
    "        self.register_buffer('inv_freq', inv_freq, persistent=False)\n",
    "        self._build_cache(max_seq_len)\n",
    "    def _build_cache(self, seq_len):\n",
    "        t = torch.arange(seq_len, dtype=torch.float32)\n",
    "        freqs = torch.outer(t, self.inv_freq)\n",
    "        emb = torch.cat((freqs, freqs), dim=-1)\n",
    "        self.register_buffer('_cached_cos', emb.cos(), persistent=False)\n",
    "        self.register_buffer('_cached_sin', emb.sin(), persistent=False)\n",
    "    def forward(self, x, seq_len):\n",
    "        if seq_len > self._cached_cos.size(0):\n",
    "            self._build_cache(max(seq_len, self.max_seq_len * 2))\n",
    "        return self._cached_cos[:seq_len, :].to(x.device), self._cached_sin[:seq_len, :].to(x.device)\n",
    "\n",
    "def rotate_half(x):\n",
    "    x1, x2 = x[..., :x.shape[-1] // 2], x[..., x.shape[-1] // 2:]\n",
    "    return torch.cat((-x2, x1), dim=-1)\n",
    "\n",
    "def apply_rotary_pos_emb(x, cos, sin):\n",
    "    cos = cos.unsqueeze(0).unsqueeze(0)\n",
    "    sin = sin.unsqueeze(0).unsqueeze(0)\n",
    "    return (x * cos) + (rotate_half(x) * sin)\n",
    "\n",
    "class RoPESelfAttention(nn.Module):\n",
    "    def __init__(self, d_model=768, nhead=12, dropout=0.1):\n",
    "        super().__init__()\n",
    "        self.d_model = d_model\n",
    "        self.nhead = nhead\n",
    "        self.head_dim = d_model // nhead\n",
    "        self.q_proj = nn.Linear(d_model, d_model, bias=False)\n",
    "        self.k_proj = nn.Linear(d_model, d_model, bias=False)\n",
    "        self.v_proj = nn.Linear(d_model, d_model, bias=False)\n",
    "        self.out_proj = nn.Linear(d_model, d_model, bias=False)\n",
    "        self.dropout = dropout\n",
    "    def forward(self, x, cos, sin):\n",
    "        b, s, _ = x.shape\n",
    "        q = self.q_proj(x).view(b, s, self.nhead, self.head_dim).transpose(1, 2)\n",
    "        k = self.k_proj(x).view(b, s, self.nhead, self.head_dim).transpose(1, 2)\n",
    "        v = self.v_proj(x).view(b, s, self.nhead, self.head_dim).transpose(1, 2)\n",
    "        q = apply_rotary_pos_emb(q, cos, sin)\n",
    "        k = apply_rotary_pos_emb(k, cos, sin)\n",
    "        out = F.scaled_dot_product_attention(q, k, v, is_causal=True, dropout_p=self.dropout if self.training else 0.0)\n",
    "        out = out.transpose(1, 2).contiguous().view(b, s, self.d_model)\n",
    "        return self.out_proj(out)\n",
    "\n",
    "class CrossAttention(nn.Module):\n",
    "    def __init__(self, d_model=768, nhead=12, dropout=0.1):\n",
    "        super().__init__()\n",
    "        self.mha = nn.MultiheadAttention(d_model, nhead, dropout=dropout, batch_first=True)\n",
    "    def forward(self, tgt, memory):\n",
    "        out, _ = self.mha(tgt, memory, memory)\n",
    "        return out\n",
    "\n",
    "class VozDistribuidaBlock(nn.Module):\n",
    "    def __init__(self, d_model=768, nhead=12, dim_feedforward=2048, dropout=0.1):\n",
    "        super().__init__()\n",
    "        self.norm1 = nn.LayerNorm(d_model)\n",
    "        self.self_attn = RoPESelfAttention(d_model, nhead, dropout)\n",
    "        self.norm2 = nn.LayerNorm(d_model)\n",
    "        self.cross_qualia = CrossAttention(d_model, nhead, dropout)\n",
    "        self.norm3 = nn.LayerNorm(d_model)\n",
    "        self.swiglu = SwiGLU(d_model, dim_feedforward, dropout)\n",
    "    def forward(self, x, qualia_mem, cos, sin):\n",
    "        x = x + self.self_attn(self.norm1(x), cos, sin)\n",
    "        x = x + self.cross_qualia(self.norm2(x), qualia_mem)\n",
    "        x = x + self.swiglu(self.norm3(x))\n",
    "        return x\n",
    "\n",
    "class VozDistribuida(nn.Module):\n",
    "    def __init__(self, vocab_size=16384, d_model=768, nhead=12, num_layers=14,\n",
    "                 dim_feedforward=2048, max_len=20480, rope_base=500000.0, dim_humor=11, dropout=0.1):\n",
    "        super().__init__()\n",
    "        self.vocab_size = vocab_size\n",
    "        self.max_len = max_len\n",
    "        self.d_model = d_model\n",
    "        self.token_embedding = nn.Embedding(vocab_size, d_model, padding_idx=0)\n",
    "        self.rope = RotaryEmbedding(d_model // nhead, max_seq_len=max_len, base=rope_base)\n",
    "        self.humor_projector = HumorProjector(dim_humor, d_model, 256)\n",
    "        self.layers = nn.ModuleList([\n",
    "            VozDistribuidaBlock(d_model, nhead, dim_feedforward, dropout) for _ in range(num_layers)\n",
    "        ])\n",
    "        self.final_norm = nn.LayerNorm(d_model)\n",
    "        self.lm_head = nn.Linear(d_model, vocab_size, bias=False)\n",
    "        self._init_weights()\n",
    "    def _init_weights(self):\n",
    "        for p in self.parameters():\n",
    "            if p.dim() > 1:\n",
    "                nn.init.xavier_uniform_(p)\n",
    "    def forward(self, input_ids, humor):\n",
    "        b, s = input_ids.shape\n",
    "        x = self.token_embedding(input_ids)\n",
    "        cos, sin = self.rope(x, s)\n",
    "        q_mem = self.humor_projector(humor)\n",
    "        for layer in self.layers:\n",
    "            x = layer(x, q_mem, cos, sin)\n",
    "        return self.lm_head(self.final_norm(x))\n",
    "\n",
    "model = VozDistribuida().to(device)\n",
    "total_params = sum(p.numel() for p in model.parameters())\n",
    "print(f'🚀 BrotherTrue Voz Distribuída compilado: {total_params:,} parâmetros ({total_params/1e6:.2f}M)!')\n",
    "print(f'📏 Janela contextual máxima RoPE: {model.max_len:,} tokens')\n"
]
