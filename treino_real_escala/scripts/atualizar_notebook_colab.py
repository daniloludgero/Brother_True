# Cell 12: Code 6 - Complete Training Loop
cell_12_lines = [
    "# @title 6. Execução do Treinamento GPU no Google Drive (FP16 + AMP)\n",
    "import json\n",
    "import torch\n",
    "from torch.utils.data import Dataset, DataLoader\n",
    "from torch.cuda.amp import GradScaler, autocast\n",
    "\n",
    "# 1. Configuração do Tokenizer com Fallback Automático\n",
    "tokenizer_path = CLOUD_WORKSPACE / 'tokenizer' / 'tokenizer_voz_novo_16k.json'\n",
    "if tokenizer_path.exists():\n",
    "    from tokenizers import Tokenizer\n",
    "    tok_raw = Tokenizer.from_file(str(tokenizer_path))\n",
    "    encode_fn = lambda t: tok_raw.encode(t).ids\n",
    "    decode_fn = lambda ids: tok_raw.decode(ids)\n",
    "else:\n",
    "    from tokenizers import ByteLevelBPETokenizer\n",
    "    print('🔹 Compilando tokenizador ByteLevel 16k a partir dos dados do Drive...')\n",
    "    tok_bpe = ByteLevelBPETokenizer()\n",
    "    corpus_files = [str(CLOUD_WORKSPACE / 'dados' / 'treino_120m.jsonl')]\n",
    "    tok_bpe.train(files=corpus_files, vocab_size=16384, min_frequency=1, special_tokens=[\n",
    "        '<pad>', '<bos>', '<eos>', '<unk>', '<|im_start|>', '<|im_end|>'\n",
    "    ])\n",
    "    tok_bpe.save(str(tokenizer_path))\n",
    "    encode_fn = lambda t: tok_bpe.encode(t).ids\n",
    "    decode_fn = lambda ids: tok_bpe.decode(ids)\n",
    "\n",
    "class ConversationalDataset(Dataset):\n",
    "    def __init__(self, jsonl_path, max_seq_len=512):\n",
    "        self.samples = []\n",
    "        with open(jsonl_path, 'r', encoding='utf-8') as f:\n",
    "            for line in f:\n",
    "                data = json.loads(line)\n",
    "                ids = encode_fn(data['text'])\n",
    "                if len(ids) > max_seq_len:\n",
    "                    ids = ids[:max_seq_len]\n",
    "                ids.append(2) # <eos>\n",
    "                h_vec = data.get('vetor_humor', [0.5]*11)\n",
    "                self.samples.append((ids, h_vec))\n",
    "    def __len__(self):\n",
    "        return len(self.samples)\n",
    "    def __getitem__(self, idx):\n",
    "        return self.samples[idx]\n",
    "\n",
    "def collate_fn(batch):\n",
    "    max_len = max(len(s[0]) for s in batch)\n",
    "    padded_ids = []\n",
    "    humors = []\n",
    "    for ids, h_vec in batch:\n",
    "        pad_size = max_len - len(ids)\n",
    "        padded_ids.append(ids + [0]*pad_size)\n",
    "        humors.append(h_vec)\n",
    "    return (\n",
    "        torch.tensor(padded_ids, dtype=torch.long),\n",
    "        torch.tensor(humors, dtype=torch.float32)\n",
    "    )\n",
    "\n",
    "train_ds = ConversationalDataset(CLOUD_WORKSPACE / 'dados' / 'treino_120m.jsonl', max_seq_len=512)\n",
    "train_loader = DataLoader(train_ds, batch_size=8, shuffle=True, collate_fn=collate_fn)\n",
    "\n",
    "scaler = GradScaler()\n",
    "optimizer = torch.optim.AdamW(model.parameters(), lr=3e-4, weight_decay=0.01)\n",
    "epochs = 3\n",
    "\n",
    "print(f'🔥 Iniciando treinamento em {len(train_ds)} amostras por {epochs} épocas...')\n",
    "model.train()\n",
    "criterion = nn.CrossEntropyLoss(ignore_index=0)\n",
    "\n",
    "for epoch in range(epochs):\n",
    "    total_loss = 0.0\n",
    "    for step, (inputs, humors) in enumerate(train_loader):\n",
    "        inputs = inputs.to(device)\n",
    "        humors = humors.to(device)\n",
    "        \n",
    "        target = inputs[:, 1:].contiguous()\n",
    "        inp = inputs[:, :-1].contiguous()\n",
    "        \n",
    "        optimizer.zero_grad()\n",
    "        with autocast():\n",
    "            logits = model(inp, humors)\n",
    "            loss = criterion(logits.view(-1, 16384), target.view(-1))\n",
    "            \n",
    "        scaler.scale(loss).backward()\n",
    "        scaler.unscale_(optimizer)\n",
    "        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)\n",
    "        scaler.step(optimizer)\n",
    "        scaler.update()\n",
    "        \n",
    "        total_loss += loss.item()\n",
    "        if (step + 1) % 50 == 0:\n",
    "            avg_step_loss = total_loss / (step + 1)\n",
    "            ppl = math.exp(min(avg_step_loss, 20))\n",
    "            print(f'Epoch [{epoch+1}/{epochs}] | Step {step+1}/{len(train_loader)} | Loss: {avg_step_loss:.4f} | PPL: {ppl:.2f}')\n",
    "\n",
    "    avg_epoch_loss = total_loss / len(train_loader)\n",
    "    print(f'✅ Época {epoch+1} Concluída! Loss Média: {avg_epoch_loss:.4f}')\n",
    "    \n",
    "    # Salvar Checkpoint no Google Drive\n",
    "    ckpt_save = CLOUD_WORKSPACE / 'checkpoints' / 'brothertrue_voz_158m_best.pt'\n",
    "    torch.save({'model': model.state_dict(), 'epoch': epoch, 'loss': avg_epoch_loss}, ckpt_save)\n",
    "    print(f'💾 Checkpoint gravado no Drive: {ckpt_save}')\n"
]
nb["cells"][12]["source"] = cell_12_lines

